"""Simple i18n for ShellCron GUI.

Usage:
    from gui.lang import L
    L.t("task_name")
    L.toggle()  # returns new lang code
    L.current  # 'en' or 'zh'
"""


class _L10n:
    """Lightweight translation with toggle."""

    def __init__(self):
        self._lang = "en"
        self._store = {}

    @property
    def current(self) -> str:
        return self._lang

    def toggle(self) -> str:
        self._lang = "zh" if self._lang == "en" else "en"
        return self._lang

    def t(self, key: str) -> str:
        """Translate key to current language."""
        d = self._store.get(self._lang, {})
        return d.get(key, key)

    def add(self, en: str, zh: str):
        """Register a bilingual string pair."""
        self._store.setdefault("en", {})[en] = en
        self._store.setdefault("zh", {})[en] = zh


